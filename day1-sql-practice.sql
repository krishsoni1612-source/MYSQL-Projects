-- Find agents with commission above average
SELECT AGENT_NAME, COMMISSION 
FROM AGENTS 
WHERE COMMISSION > (SELECT AVG(COMMISSION) FROM AGENTS);

-- Count agents per working area
SELECT WORKING_AREA, COUNT(*) as A_count 
FROM AGENTS 
GROUP BY WORKING_AREA 
ORDER BY A_count DESC;

-- Find top 3 highest commission agents
SELECT AGENT_NAME, WORKING_AREA, COMMISSION 
FROM AGENTS 
ORDER BY COMMISSION DESC 
LIMIT 3;

-- Agents in Bangalore or London
SELECT AGENT_NAME, WORKING_AREA, COMMISSION 
FROM AGENTS 
WHERE WORKING_AREA IN ('Bangalore', 'London');

-- Working areas with average commission above 0.13
SELECT WORKING_AREA, AVG(COMMISSION) as A_commission 
FROM AGENTS 
GROUP BY WORKING_AREA 
HAVING AVG(COMMISSION) > 0.13;
