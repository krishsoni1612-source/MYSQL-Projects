-- min max querys
SELECT MAX(COMMISSION) FROM AGENTS;
SELECT MIN(COMMISSION) FROM AGENTS;

-- create group with avg
SELECT WORKING_AREA , AVG(COMMISSION) FROM AGENTS GROUP BY WORKING_AREA;

-- print avg 
